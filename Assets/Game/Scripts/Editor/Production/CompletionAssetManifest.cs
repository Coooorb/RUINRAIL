            AssetDatabase.LoadAssetAtPath<MusicCatalog>("Assets/Game/ScriptableObjects/Audio/MusicCatalog.asset");



        /// <summary>Ammo icons are keyed by the AmmoItemDefinition that carries that ammo type.</summary>
        private static string AmmoIconStatus(AmmoType ammo)
        {
            foreach (var definition in LoadAll<AmmoItemDefinition>())
                if (definition.AmmoType == ammo) return definition.HasIcon ? Integrated : Missing;
            return Missing;
        }

        /// <summary>A biome tile is final once a tile asset exists outside the shared placeholder folder.</summary>
        private static (string Status, string Source) TileStatus(Biome biome, string role)
        {
            var finalPath = $"Assets/Game/Art/Tiles/{biome}/{biome.ToString().ToLowerInvariant()}_{role}.asset";
            if (AssetDatabase.LoadAssetAtPath<UnityEngine.Tilemaps.TileBase>(finalPath) != null)
                return (Integrated, finalPath);

            var placeholder = $"Assets/Game/Art/Tiles/_Placeholder/Placeholder_{ToPascal(role)}.asset";
            return string.IsNullOrEmpty(AssetDatabase.AssetPathToGUID(placeholder))
                ? (Missing, "—")
                : (Placeholder, placeholder + " (shared by all 3 biomes)");
        }

        // ---- Characters and animation ----
        private static void AddCharacterRoles(Report r)
        {
            var sets = LoadAll<CharacterAnimationSet>();

            void Actor(string actorId, string kind, string[] keys, string canvas)
            {
                var set = sets.FirstOrDefault(s => string.Equals(s.ActorId, actorId, StringComparison.OrdinalIgnoreCase));
                var required = keys.Length * AnimationRules.AllFacings.Length;
                var missing = set != null ? set.Missing(keys).Count : required;
                r.Roles.Add(new Role
                {
                    Category = "Character source sprites",
                    RoleId = actorId,
                    Owner = kind == "Player" ? "PlayerAnimationDriver" : "EnemyAnimationDriver",
                    AssetType = "Directional sprite sheet",
                    Spec = $"{kind}, 8 facings, art/106 section 3 canvas {canvas}, 32 PPU",
                    Status = set != null && missing == 0 ? Integrated : Missing
                });
                r.Roles.Add(new Role
                {
                    Category = "Character animation clip roles",
                    RoleId = actorId,
                    Owner = "CharacterAnimationSet",
                    AssetType = "SpriteAnimationClip set",
                    Spec = $"{string.Join("/", keys)} x 8 facings = {required} clip roles ({missing} outstanding), {AnimationRules.MinFps}-{AnimationRules.MaxFps} fps (art/103)",
                    Status = set == null ? Missing : missing == 0 ? Integrated : Placeholder,
                    SourcePath = set != null ? AssetDatabase.GetAssetPath(set) : "—"
                });
            }

            Actor(AnimationAssetAudit.PlayerActorId, "Player", AnimationRules.PlayerClipKeys, "~32x48 px");
            foreach (var e in LoadAll<EnemyDefinition>()) Actor(e.Id, "Enemy", AnimationRules.EnemyClipKeys, "16-64 px by archetype");
            foreach (var e in LoadAll<EliteDefinition>()) Actor(e.Id, "Elite", AnimationRules.EnemyClipKeys, "~48-64+ px");
            foreach (var b in LoadAll<BossDefinition>()) Actor(b.Id, "Boss", AnimationRules.EnemyClipKeys, "~64-128 px");
        }

