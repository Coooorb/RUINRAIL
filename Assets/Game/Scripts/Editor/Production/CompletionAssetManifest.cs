    /// <summary>
    /// TASK 149 completion manifest (production/134): enumerates every final asset role from the repository itself —
    /// definitions, code role ids and existing assets — and reconciles the totals against the TASK-148 baselines in
    /// production/135. It never keeps a count list of its own: every number is derived, and a delta is reported with
    /// the code/data source that produced it. Audit only; it changes no gameplay data.
    /// </summary>
    public static class CompletionAssetManifest
    {
        public const string ReportPath = "TestResults/completion_asset_manifest.md";
        /// <summary>The generated pixel font, which replaces the builtin LegacyRuntime.ttf in the release path.</summary>
        public const string PixelFontPath = "Assets/Game/Resources/Fonts/ruinrail_pixel.fontsettings";
        /// <summary>production/134 status vocabulary.</summary>
        public const string Missing = "MISSING";
        public const string Placeholder = "PLACEHOLDER";
        public const string Integrated = "INTEGRATED";

        public sealed class Role
        {
            public string Category;
            public string RoleId;
            public string Owner;
            public string AssetType;
            public string Spec;
            public string Status;
            /// <summary>Where the role's asset currently resolves from, if anywhere.</summary>
            public string SourcePath = "—";
            /// <summary>TASK 151 convention path a final asset must land at (AssetNamingConvention).</summary>
            public string ExpectedSourcePath = string.Empty;
            /// <summary>The existing runtime object that binds the asset, so a replacement changes no gameplay id.</summary>
            public string BindingPoint = string.Empty;
        }

        public sealed class Reconciliation
        {
            public string Item;
            public int Baseline;
            public int Current;
            public string Source;
            /// <summary>Set only for a delta TASK 149 verified against the repository and explained. Empty means "must match".</summary>
            public string ExplainedDelta = string.Empty;
            public bool Match => Baseline == Current;
            public bool Explained => ExplainedDelta.Length > 0;
            public string Result => Match ? "EXACT" : Explained ? "DELTA (explained)" : "DELTA (unexplained)";
        }

        public sealed class Report
        {
            public readonly List<Role> Roles = new();
            public readonly List<Reconciliation> Reconciliations = new();
            public readonly List<string> LiveServiceBlockers = new();
            public readonly List<string> EngineeringBlockers = new();
            public readonly List<string> HumanGates = new();
            public string ReleasePlatformScope = string.Empty;

            public int Count(string status) => Roles.Count(r => r.Status == status);
            /// <summary>True when nothing drifted silently: every count either matches the baseline or carries a verified explanation.</summary>
            public bool AllReconciled => Reconciliations.All(r => r.Match || r.Explained);
            public IEnumerable<string> Categories => Roles.Select(r => r.Category).Distinct();

            public string ToMarkdown()
            {
                var sb = new StringBuilder();
                sb.AppendLine("# RUINRAIL Completion Asset Manifest (TASK 149)");
                sb.AppendLine();
                sb.AppendLine("> Generated by `RuinRail/Production/Generate Completion Asset Manifest`. Do not hand-edit: regenerate.");
                sb.AppendLine("> Status vocabulary: production/134. Runner rules: production/133. Art direction: art/106.");
                sb.AppendLine();
                sb.AppendLine($"Total final asset roles: **{Roles.Count}** — {Count(Integrated)} INTEGRATED, {Count(Placeholder)} PLACEHOLDER, {Count(Missing)} MISSING.");
                sb.AppendLine($"TASK-148 baseline reconciliation: **{(AllReconciled ? "RECONCILED" : "UNEXPLAINED DRIFT")}** — {Reconciliations.Count(r => r.Match)}/{Reconciliations.Count} counts match exactly, {Reconciliations.Count(r => !r.Match)} explained delta(s).");
                sb.AppendLine();

                sb.AppendLine("## Baseline Reconciliation (production/135)");
                sb.AppendLine();
                sb.AppendLine("| Item | TASK-148 baseline | Current | Source of truth | Result |");
                sb.AppendLine("|---|---:|---:|---|---|");
                foreach (var r in Reconciliations)
                {
                    sb.AppendLine($"| {r.Item} | {r.Baseline} | {r.Current} | {r.Source} | {r.Result} |");
                }

                foreach (var r in Reconciliations.Where(x => !x.Match))
                {
                    sb.AppendLine();
                    sb.AppendLine($"**Delta — {r.Item}:** {r.ExplainedDelta}");
                }

                sb.AppendLine();
                sb.AppendLine("## Asset Roles by Category");
                foreach (var category in Categories)
                {
                    var rows = Roles.Where(r => r.Category == category).ToList();
                    sb.AppendLine();
                    sb.AppendLine($"### {category} — {rows.Count} roles ({rows.Count(r => r.Status == Integrated)} INTEGRATED / {rows.Count(r => r.Status == Placeholder)} PLACEHOLDER / {rows.Count(r => r.Status == Missing)} MISSING)");
                    sb.AppendLine();
                    sb.AppendLine("| Role id | Runtime owner | Asset type | Required spec | Expected source path | Binding point | Current source | Status |");
                    sb.AppendLine("|---|---|---|---|---|---|---|---|");
                    foreach (var row in rows)
                    {
                        var expected = row.ExpectedSourcePath.Length > 0 ? row.ExpectedSourcePath : "—";
                        var binding = row.BindingPoint.Length > 0 ? row.BindingPoint : "—";
                        sb.AppendLine($"| {row.RoleId} | {row.Owner} | {row.AssetType} | {row.Spec} | {expected} | {binding} | {row.SourcePath} | {row.Status} |");
                    }
                }

                sb.AppendLine();
                sb.AppendLine("## Live Online Service Blockers");
                sb.AppendLine();
                foreach (var b in LiveServiceBlockers) sb.AppendLine($"- {b}");

                sb.AppendLine();
                sb.AppendLine("## Engineering / Release Blockers");
                sb.AppendLine();
                foreach (var b in EngineeringBlockers) sb.AppendLine($"- {b}");

                sb.AppendLine();
                sb.AppendLine("## Human / External Approval Still Required");
                sb.AppendLine();
                foreach (var g in HumanGates) sb.AppendLine($"- {g}");

                sb.AppendLine();
                sb.AppendLine("## Release Platform Scope");
                sb.AppendLine();
                sb.AppendLine(ReleasePlatformScope);
                return sb.ToString();
            }
        }

        [MenuItem("RuinRail/Production/Generate Completion Asset Manifest")]
        public static void GenerateMenu() => Debug.Log(WriteReport().ToMarkdown());

        public static Report WriteReport()
        {
            var report = Generate();
            Directory.CreateDirectory(Path.GetDirectoryName(ReportPath) ?? "production");
            File.WriteAllText(ReportPath, report.ToMarkdown());
            return report;
        }

        public static Report Generate()
        {
            var r = new Report();
            AddCharacterRoles(r);
            AddWeaponRoles(r);
            AddItemIconRoles(r);
            AddEnvironmentRoles(r);
            AddWorldObjectRoles(r);
            AddUiRoles(r);
            AddVfxRoles(r);
            AddAudioRoles(r);
            AddNetworkPrefabRoles(r);
            ApplyNamingConvention(r);
            AddReconciliations(r);
            AddBlockers(r);
            return r;
        }

        /// <summary>TASK 151: stamp each role with where its final asset belongs and what already binds it.</summary>
        private static void ApplyNamingConvention(Report r)
        {
            foreach (var role in r.Roles)
            {
                var placement = AssetNamingConvention.For(role.Category, role.RoleId);
                role.ExpectedSourcePath = placement.ExpectedSourcePath;
                role.BindingPoint = placement.BindingPoint;
            }
        }

        // ---- status resolution ----


        /// <summary>
        /// A role is INTEGRATED when its asset actually resolves at the convention path, PLACEHOLDER when only dev art
        /// stands in, and MISSING otherwise. Resolving this from the filesystem rather than hard-coding it is what lets
        /// the batch gates and the final audit tell the truth as art lands.
        /// </summary>
        private static string StatusOfSprite(string assetPath) =>
            AssetDatabase.LoadAssetAtPath<Sprite>(assetPath) != null ? Integrated : Missing;

        /// <summary>Lighting is final once its tint has left neutral white for the biome's authored look.</summary>
        private static string LightingStatus(Biome biome)
        {
            var profile = AssetDatabase.LoadAssetAtPath<RuinRail.Presentation.BiomeLightingProfile>(
                $"Assets/Game/ScriptableObjects/Presentation/Lighting_{biome}.asset");
            if (profile == null) return Missing;

            var c = profile.GlobalLightColor;
            var neutral = Mathf.Approximately(c.r, 1f) && Mathf.Approximately(c.g, 1f) && Mathf.Approximately(c.b, 1f);
            return neutral ? Placeholder : Integrated;
        }

