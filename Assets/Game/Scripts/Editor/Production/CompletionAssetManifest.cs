            CountLines("PROTOTYPE", new[] { "Assets/Game/Scripts", "Assets/Game/ScriptableObjects" }, new[] { ".cs", ".asset" });

        public static int NonAllocCallCount() =>
            CountLines("Physics2D.", new[] { "Assets/Game/Scripts" }, new[] { ".cs" }, "NonAlloc");

        public static int NonAllocFileCount() =>
            SourceFiles(new[] { "Assets/Game/Scripts" }, new[] { ".cs" })
                .Count(f => File.ReadLines(f).Any(l => l.Contains("Physics2D.") && l.Contains("NonAlloc")));

        private static int CountLines(string needle, string[] roots, string[] extensions, string alsoOnLine = null) =>
            SourceFiles(roots, extensions)
                .SelectMany(File.ReadLines)
                .Count(line => line.Contains(needle) && (alsoOnLine == null || line.Contains(alsoOnLine)));

        /// <summary>Authored runtime sources: tests and editor tooling never hold a gameplay tunable or a shipped call site.</summary>
        private static IEnumerable<string> SourceFiles(string[] roots, string[] extensions) =>
            roots.Where(Directory.Exists)
                .SelectMany(root => Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories))
                .Where(f => extensions.Contains(Path.GetExtension(f)))
                .Select(f => f.Replace('\\', '/'))
                .Where(f => !f.Contains("/Tests/") && !f.Contains("/Editor/"));

